/** 常任委員会で全会一致とされ、12月15日に異議なく可決された議案 */
function ordinance(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  committeeNote?: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committeeNote ?? ""}${input.committee}は、全会一致で可決すべきものとしました。

## 審議の経過
12月15日の本会議で異議なく可決されました。`,
  };
}

/** 指定管理者の指定（議案第107〜109号）。笠間観光協会を指定する */
function kankoKyokai(number: number, facility: string, note?: string) {
  return ordinance({
    number,
    title: `指定管理者の指定について（${facility}）`,
    summary: `${facility}の管理を、平成29年4月から5年間、一般社団法人笠間観光協会に任せる（指定管理者に指定する）議案。`,
    points: `- 指定管理者は、市の施設の管理を市に代わって行う団体です。指定には議会の議決が必要です（地方自治法第244条の2第6項）
- ${facility}の指定管理者に、一般社団法人笠間観光協会を指定します
- 期間は平成29年4月1日から平成34年3月31日までの5年間です
- 10月11日の指定管理者選定審議会で、事業計画が施設の目的に合い、市民サービスの向上と安定した管理運営が見込めるとして、適当と判断されました`,
    committee: "総務産業委員会",
    committeeNote: note,
  });
}

