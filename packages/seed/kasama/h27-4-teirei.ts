/** 12月15日に議決された議案（委員会審査あり）。split なら起立採決で賛成多数 */
function passed(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: string;
  split?: boolean;
  question?: string;
  debate?: string;
}): KasamaBill {
  const result = input.split
    ? "起立による採決で賛成多数で可決された。"
    : "全会一致で可決。";
  const process = input.split
    ? `12月15日の本会議で起立により採決され、賛成多数で可決されました（${UNPUBLISHED_NOTE}）。`
    : "12月15日の本会議で異議なく可決されました。";
  const sections = [
    `## ポイント解説\n${input.points}`,
    input.question ? `## 議会での質疑\n${input.question}` : null,
    `## 委員会での審査\n${input.committee}`,
    input.debate ? `## 討論\n${input.debate}` : null,
    `## 審議の経過\n${process}`,
  ].filter((s): s is string => s !== null);
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    ...(input.split ? { vote: { unpublished: true as const } } : {}),
    summary: `${input.summary}${result}`,
    body: sections.join("\n\n"),
  };
}

/** 指定管理者の指定（議案第83〜85号） */
function designation(input: {
  number: number;
  facility: string;
  manager: string;
  period: string;
  reason: string;
  committeeNote?: string;
}): KasamaBill {
  return passed({
    number: input.number,
    title: `指定管理者の指定について（${input.facility}）`,
    summary: `${input.facility}の管理を、${input.manager}に${input.period}任せる（指定管理者に指定する）議案。`,
    points: `- 市の施設の管理を民間の団体などに任せる仕組み（指定管理者制度）で、${input.facility}を管理する団体を決めます。指定には議会の議決が必要です
- 指定するのは${input.manager}、期間は${input.period}です
- ${input.reason}
- 指定管理者選定審議会から、候補者として適当であるとの答申を受けています`,
    committee: `${input.committeeNote ?? ""}総務産業委員会は、原案のとおり可決すべきものとしました。`,
  });
}

