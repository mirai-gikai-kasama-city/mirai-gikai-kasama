/** 常任委員会で可決すべきとされ、9月17日に異議なく可決された議案 */
function unanimous(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  /** 委員会が全会一致と報告したとき true */
  committeeUnanimous?: boolean;
  committeeNote?: string;
}): KasamaBill {
  const decision = input.committeeUnanimous
    ? "全会一致で原案のとおり可決すべきものとしました"
    : "原案のとおり可決すべきものとしました";
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committeeNote ?? ""}${input.committee}は、${decision}。

## 審議の経過
9月17日の本会議で異議なく可決されました。`,
  };
}

