type Committee = "総務産業委員会" | "教育福祉委員会" | "建設土木委員会";

/** 常任委員会・予算特別委員会で全会一致とされ、異議なく可決された議案 */
function ordinance(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee | "予算特別委員会";
  committeeNote?: string;
  /** 3月2日に議決した令和3年度の補正予算のとき true */
  decidedOnSecondDay?: boolean;
}): KasamaBill {
  const decidedOn = input.decidedOnSecondDay ? SECOND_DAY : LAST_DAY;
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committeeNote ?? ""}${input.committee}は、全会一致で可決すべきものとしました。

## 審議の経過
${input.decidedOnSecondDay ? "3月2日" : "3月18日"}の本会議で異議なく可決されました。`,
  };
}

