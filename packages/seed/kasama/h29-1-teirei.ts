/** 常任委員会で全会一致とされ、3月16日に異議なく可決された議案 */
function ordinance(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  committeeNote?: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committeeNote ?? ""}${input.committee}は、全会一致で可決すべきものとしました。

## 審議の経過
3月16日の本会議で異議なく可決されました。`,
  };
}

/** 起立で採決され、賛成多数で可決された議案（3月16日） */
function splitBill(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committeeNote: string;
  debate: string;
}): KasamaBill {
  const split = standing(input.number);
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    vote: split.vote,
    summary: `${input.summary}起立による採決で、${split.tally}で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committeeNote}

## 討論
${input.debate}

## 審議の経過
3月16日の本会議で起立により採決され、${split.tally}で可決されました。${STANDING_VOTE}${ABSENT_NOTE}`,
  };
}

