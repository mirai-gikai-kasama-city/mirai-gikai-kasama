/** 専決処分の報告（6月1日に異議なく承認） */
function senketsu(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
}): KasamaBill {
  return {
    billNumberLabel: `報告第${input.number}号`,
    title: input.title,
    resultLabel: "原案承認",
    decidedOn: FIRST_DAY,
    source: "minutes",
    summary: `${input.summary}異議なく承認された。`,
    body: `## ポイント解説
- ${SENKETSU_NOTE}
${input.points}

## 審議の経過
委員会での審査は省略され、6月1日に異議なく承認されました。`,
  };
}

/** 常任委員会で全会一致とされ、6月15日に異議なく可決された議案 */
function ordinance(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  committeeNote?: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committeeNote ?? ""}${input.committee}は、全会一致で可決すべきものとしました。

## 審議の経過
6月15日の本会議で異議なく可決されました。`,
  };
}

