function bill(
  number: number,
  title: string,
  summary: string,
  body: string,
  vote?: KasamaBill["vote"]
): KasamaBill {
  return {
    billNumberLabel: `議案第${number}号`,
    title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    ...(vote ? { vote } : {}),
    source: "minutes",
    summary,
    body,
  };
}

/** 委員会も本会議も異議なく決まった議案 */
