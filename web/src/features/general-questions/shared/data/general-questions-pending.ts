import type { GeneralQuestionRecord } from "@mirai-gikai/shared/council/types";

const R8_4_LIST_PDF =
  "https://www.city.kasama.lg.jp/data/doc/1794270522_doc_56_0.pdf";

type Outline = { title: string; points: (string | [string, string[]])[] };

function r84(input: {
  order: number;
  dayIndex: 1 | 2;
  memberName: string;
  outline: Outline[];
}): GeneralQuestionRecord {
  return {
    id: `kasama-r8-4-teirei-${input.order}`,
    sessionKey: "kasama-r8-4-teirei",
    sessionName: "令和8年第4回定例会",
    questionDate: null,
    dayIndex: input.dayIndex,
    order: input.order,
    memberName: input.memberName,
    familyName: input.memberName.split(" ")[0],
    faction: null,
    isRepresentative: false,
    format: "一問一答",
    items: input.outline.map((item) => item.title),
    outline: input.outline.map((item) => ({
      title: item.title,
      points: item.points.map((point) =>
        typeof point === "string"
          ? { text: point, subPoints: [] }
          : { text: point[0], subPoints: point[1] }
      ),
    })),
    videoUrl: null,
    minutesUrl: null,
    sourceUrl: R8_4_LIST_PDF,
    pdfUrl: R8_4_LIST_PDF,
  };
}

