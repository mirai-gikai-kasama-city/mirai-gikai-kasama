/** 専決処分の報告（報告第1〜8号）。6月1日に一括議題、1件ずつ採決 */
function senketsu(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  /** 質疑の内容など */
  extra?: string;
}): KasamaBill {
  return {
    billNumberLabel: `報告第${input.number}号`,
    title: input.title,
    resultLabel: "原案承認",
    decidedOn: FIRST_DAY,
    source: "minutes",
    summary: `${input.summary}異議なく承認された。`,
    body: `## ポイント解説
- ${SENKETSU_NOTE}
${input.points}

## 審議の経過
初日の6月1日に、報告第1号から第8号までの8件をまとめて審議しました。${input.extra ?? ""}委員会への付託と討論を省いて1件ずつ採決され、この報告は異議なく承認されました。`,
  };
}

