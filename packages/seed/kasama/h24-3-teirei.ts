/** 会計の正式な名前（「市立病院事業会計」は「笠間市立病院事業会計」） */
const accountName = (account: string) =>
  account.startsWith("市立") ? `笠間${account}` : `笠間市${account}`;

/** 常任委員会で全会一致とされ、9月21日に異議なく可決された議案（議案第58〜79号） */
function passed(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committee}

## 審議の経過
9月21日の本会議で異議なく可決されました。`,
  };
}

/** 平成24年度の補正予算（議案第70〜78号）。所管の常任委員会で全会一致 */
function supplementary(input: {
  number: number;
  account: string;
  issue: string;
  detail: string;
  committee: string;
}): KasamaBill {
  return passed({
    number: input.number,
    title: `平成２４年度${accountName(input.account)}補正予算（第${input.issue}号）`,
    summary: `平成24年度の${input.account}の額を見直す補正予算。`,
    points: `- ${input.detail}`,
    committee: `${input.committee}は、全会一致で可決すべきものとしました。`,
  });
}

