/** 平成20年度予算のうち、本会議で異議なく可決されたもの */
function budget(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  /** 予算特別委員会の採決が挙手多数だったとき true */
  committeeSplit?: boolean;
  /** 委員会での質疑など */
  extra?: string;
}): KasamaBill {
  const committeeResult = input.committeeSplit
    ? "この会計は挙手多数で可決すべきものとしました。"
    : "この会計は挙手全員で可決すべきものとしました。";
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: input.committeeSplit
      ? `${input.summary}委員会では賛成多数だったが、本会議では異議なく可決された。`
      : `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${BUDGET_COMMITTEE}${input.extra ?? ""}${committeeResult}

## 審議の経過
3月21日の本会議で、この会計への討論はなく、異議なく可決されました。`,
  };
}

