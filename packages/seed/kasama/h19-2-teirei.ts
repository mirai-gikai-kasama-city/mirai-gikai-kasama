/** 常任委員会で全会一致とされ、6月15日に異議なく可決された議案 */
function passed(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: keyof typeof COMMITTEES;
  extra?: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${COMMITTEES[input.committee]}で執行部から説明を受けて審査し、全会一致で原案のとおり可決すべきものとしました。

## 審議の経過
6月4日に提案され、6月8日に委員会に付託されました。${input.extra ? `${input.extra}` : ""}委員会での審査の後、6月15日の本会議で異議なく可決されました。`,
  };
}

