/** 初日に委員会の審査を省いて異議なく承認された専決処分の報告 */
function senketsu(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  extra?: string;
}): KasamaBill {
  return {
    billNumberLabel: `報告第${input.number}号`,
    title: input.title,
    resultLabel: "原案承認",
    decidedOn: FIRST_DAY,
    source: "minutes",
    summary: `${input.summary}異議なく承認された。`,
    body: `## ポイント解説
- ${SENKETSU_NOTE}
${input.points}

## 審議の経過
${input.extra ?? ""}委員会での審査は省略され、6月1日に異議なく承認されました。`,
  };
}

