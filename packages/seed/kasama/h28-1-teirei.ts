/** 常任委員会で審査され、3月17日に可決された条例などの議案 */
function ordinance(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  committeeNote?: string;
  /** 委員会での結論の言い方（既定は全会一致） */
  committeeResult?: string;
  /** 起立で採決されたとき、委員会での反対討論の内容 */
  dissent?: string;
}): KasamaBill {
  const split = input.dissent !== undefined;
  const committeeResult =
    input.committeeResult ?? (split ? "賛成多数" : "全会一致");
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    vote: split ? SPLIT_VOTE : undefined,
    summary: `${input.summary}${split ? "起立による採決で賛成多数で可決された。" : "全会一致で可決。"}`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committeeNote ?? ""}${input.dissent ?? ""}${input.committee}は、${committeeResult}で可決すべきものとしました。

## 審議の経過
${
  split
    ? `3月17日の本会議で起立により採決され、賛成多数で可決されました${UNPUBLISHED_NOTE}。`
    : "3月17日の本会議で異議なく可決されました。"
}`,
  };
}

