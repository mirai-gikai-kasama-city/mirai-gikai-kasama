/** 市営住宅の未払い家賃についての和解（議案第70〜74号） */
function settlementOfRent(input: {
  number: number;
  amount: string;
  monthly: string;
}): KasamaBill {
  const key = `議案${input.number}`;
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: "和解について",
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    vote: standing(key).vote,
    summary: `市営住宅の未払い家賃など${input.amount}を、毎月${input.monthly}ずつ分けて支払ってもらう内容で、入居者と裁判所で和解する議案。起立による採決で、${standing(key).tally}で可決。`,
    body: `## ポイント解説
- 市営住宅の家賃などを払っていない入居者との間で、民事訴訟法上の和解（裁判所での話し合いによる解決）をするため、議会の議決を求める議案です（地方自治法第96条第1項第12号）
- 支払う義務のある額は${input.amount}で、毎月${input.monthly}ずつ分けて支払います。和解の内容が守られない場合の措置も定めています
- 相手方は一括での支払いが難しい一方、住み続けることを望み、和解したいと申し出ました
- 裁判所は笠間簡易裁判所です
- 同じ内容の和解が議案第70号から第74号まで5件あり、この議案はそのうちの1件です

## 質疑
9月4日の質疑では、5件について、法的な手続きをとる前の対応や相手方の生活の状況を問う質問がありました。市は、管理を委託している茨城県住宅管理センターが毎月電話や訪問で督促してきたが約束が守られず未払いが増えたこと、職員が直接面談し、5人とも職業と収入があり生活困難とは認められないこと、ほかの入居者との公平性にも問題が出てきたことを答えました。

## 委員会での審査
建設土木委員会は、全会一致で可決すべきものとしました。

## 討論
本会議では反対の討論がありました。市営住宅は所得の低い人を助ける制度であり、民事訴訟を通じて強制執行もできる状態にすることは困難を抱える世帯を追い詰めることになる、市は市民に寄り添って支援すべきだ、という主張でした。

## 審議の経過
9月15日の本会議で起立により採決され、${standing(key).tally}で可決されました。${STANDING_VOTE}`,
  };
}

