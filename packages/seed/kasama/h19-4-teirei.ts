/** 委員会では全会一致だったが、12月17日の本会議で起立により賛成多数で可決された議案 */
function standing(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  extra?: string;
  /** 本会議の討論の段落（無ければ「討論はなく」） */
  debate?: string;
}): KasamaBill {
  const debate = input.debate
    ? `${input.debate}`
    : "12月17日の本会議では、この議案についての討論はありませんでした。";
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    vote: { unpublished: true },
    source: "minutes",
    summary: `${input.summary}${SPLIT_SUMMARY}`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${COMMITTEES[input.committee]}で執行部から説明を受けて審査し、全会一致で可決すべきものとしました。${input.extra ?? ""}

## 審議の経過
12月3日に提案され、委員会での審査の後、12月17日の本会議で採決されました。${debate}起立により採決され、賛成多数で可決されました。${UNPUBLISHED_NOTE}`,
  };
}

