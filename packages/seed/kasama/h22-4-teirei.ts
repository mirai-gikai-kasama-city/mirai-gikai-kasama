/** 常任委員会で全会一致で可決すべきものとされ、11月15日に異議なく可決された議案 */
function passed(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: keyof typeof COMMITTEES;
  /** 委員長の報告にある質疑など */
  extra: string;
  /** 11月4日の本会議の質疑など（あれば） */
  floor?: string;
  /** 11月1日の説明のされ方（まとめて説明されたときなど） */
  intro?: string;
}): KasamaBill {
  const floor = input.floor ? `${input.floor}\n\n` : "";
  const intro = input.intro ?? "11月1日に提案され";
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${floor}${COMMITTEES[input.committee]}で執行部から説明を受けて審査しました。${input.extra}全会一致で原案のとおり可決すべきものとしました。

## 審議の経過
${intro}、4日の本会議で委員会に付託されました。11月15日の本会議で、この議案への討論はなく、異議なく可決されました。`,
  };
}

