/** 常任委員会で全会一致で可決すべきものとされ、9月19日に異議なく可決された議案 */
function ordinance(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  committeeNote?: string;
  extra?: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}異議なく可決された。`,
    body: `## ポイント解説
${input.points}
${input.extra ?? ""}
## 委員会での審査
${input.committeeNote ?? ""}${input.committee}は、全会一致で原案のとおり可決すべきものとしました。

## 審議の経過
9月19日の本会議で、討論の通告は無く、異議なく可決されました。`,
  };
}

