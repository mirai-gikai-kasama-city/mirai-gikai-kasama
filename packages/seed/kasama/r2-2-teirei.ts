/** 常任委員会で全会一致とされ、6月12日に異議なく可決された議案 */
function ordinance(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  committeeNote?: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committeeNote ?? ""}${input.committee}は、全会一致で可決すべきものとしました。

## 審議の経過
6月12日の本会議で異議なく可決されました。`,
  };
}

