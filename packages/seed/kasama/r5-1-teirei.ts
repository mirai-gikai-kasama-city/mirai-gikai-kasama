/** 常任委員会で全会一致とされ、3月17日に異議なく可決された議案 */
function ordinance(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  /** 委員会での主な質疑。結論の前に置く */
  committeeNote?: string;
  /** 本会議の議案質疑（3月2日） */
  question?: string;
}): KasamaBill {
  const question = input.question
    ? `\n\n## 議会での質疑\n${input.question}`
    : "";
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}${question}

## 委員会での審査
${input.committeeNote ?? ""}${input.committee}は、全会一致で可決すべきものとしました。

## 審議の経過
3月17日の本会議で異議なく可決されました。`,
  };
}

