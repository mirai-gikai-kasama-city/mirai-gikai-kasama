/** 12月2日に提案され、常任委員会で全会一致とされ、12月16日に異議なく可決された議案 */
function passed(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  extra?: string;
  /** 12月5日の本会議の質疑などの段落 */
  process?: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${COMMITTEES[input.committee]}で執行部から説明を受けて審査し、全会一致で可決すべきものとしました。${input.extra ?? ""}

## 審議の経過
12月2日に提案され、${input.process ?? ""}委員会での審査の後、12月16日の本会議で異議なく可決されました。`,
  };
}

/** 平成20年度の補正予算（特別会計・企業会計） */
function hosei(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: Committee;
  extra?: string;
}): KasamaBill {
  return passed({
    number: input.number,
    title: input.title,
    summary: input.summary,
    points: `- 年度の途中で、事業費の決定や見込みの変化に合わせて、平成20年度の予算を調整する補正予算です
${input.points}`,
    committee: input.committee,
    extra: input.extra,
  });
}

/** 一部事務組合の議会に送る議員の選挙（指名推選。番号が無い） */
function unionElection(input: {
  number: number;
  body: string;
  seats: number;
  members: string;
}): KasamaBill {
  return unnumbered("選挙", input.number, {
    title: `${input.body}議会議員選挙について`,
    resultLabel: "当選",
    decidedOn: LAST_DAY,
    summary: `${input.body}の議会に、笠間市議会から送る議員${input.seats}人を選ぶ選挙。議長の指名で${input.members}が当選した。`,
    body: `${input.body}は、${UNION_NOTE}。組合の規約第5条第2項により、その議会の議員${input.seats}人を、笠間市議会の議員の中から選びます。議長・副議長が新しくなった12月16日に、委員の選任に続いて行われました。投票ではなく議長が指名する方法（指名推選。地方自治法第118条第2項）をとることに異議はなく、議長の指名どおり${input.members}が当選しました。`,
  });
}

