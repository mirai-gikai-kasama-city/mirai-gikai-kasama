/** 常任委員会で全会一致とされ、3月18日に異議なく可決された議案（議案第9〜29号・第50号） */
function passed(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: string;
}): KasamaBill {
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${input.committee}

## 審議の経過
3月18日の本会議で異議なく可決されました。`,
  };
}

