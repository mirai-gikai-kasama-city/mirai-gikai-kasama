/** 常任委員会で全会一致で可決すべきものとされ、12月15日に異議なく可決された議案 */
function passed(input: {
  number: number;
  title: string;
  summary: string;
  points: string;
  committee: keyof typeof COMMITTEES;
  /** 委員長の報告にある質疑など */
  extra: string;
  /** 12月3日の本会議での質疑（無ければ省略） */
  question?: string;
}): KasamaBill {
  const question = input.question
    ? `11月30日に提案され、12月3日の本会議で質疑がありました。${input.question}その後、委員会に付託されました。`
    : "11月30日に提案され、12月3日の本会議で質疑はなく、委員会に付託されました。";
  return {
    billNumberLabel: `議案第${input.number}号`,
    title: input.title,
    resultLabel: "原案可決",
    decidedOn: LAST_DAY,
    source: "minutes",
    summary: `${input.summary}全会一致で可決。`,
    body: `## ポイント解説
${input.points}

## 委員会での審査
${COMMITTEES[input.committee]}で執行部から説明を受けて審査しました。${input.extra}全会一致で原案のとおり可決すべきものとしました。

## 審議の経過
${question}12月15日の本会議で、討論はなく、異議なく可決されました。`,
  };
}

